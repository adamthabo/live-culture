# writes src/09-cities.js: the world's towns and cities from Natural Earth's populated places (1:50m; public domain), for naming the
# place a finger taps on the Earth ("near Boston"). usage: python3 -I tools/gen_cities.py <ne_50m_populated_places_simple.geojson>
import json, sys
d = json.load(open(sys.argv[1], encoding='utf-8'))
SHORT = {'United States of America': 'United States', 'United Republic of Tanzania': 'Tanzania', 'Democratic Republic of the Congo': 'DR Congo',
         'Republic of the Congo': 'Congo', 'Central African Republic': 'Central African Rep.', 'Bosnia and Herzegovina': 'Bosnia',
         'United Arab Emirates': 'UAE', 'Dominican Republic': 'Dominican Rep.', 'Russian Federation': 'Russia', 'Czechia': 'Czechia'}
rows = []
for f in d['features']:
    p = f['properties']; n = (p.get('name') or '').strip(); c = (p.get('adm0name') or '').strip()
    if not n or '|' in n or '|' in c: continue
    c = SHORT.get(c, c)
    rows.append('%s|%s|%.2f|%.2f' % (n, c, p['latitude'], p['longitude']))
js = ('/* ---------- the world\'s towns and cities (Natural Earth, populated places at 1:50 million; public domain): the nearest names the place\n'
      '   a finger taps on the Earth. Generated by tools/gen_cities.py ---------- */\n'
      'var CITIES=(function(){var L=' + json.dumps('\n'.join(rows), ensure_ascii=False) + '.split("\\n").map(function(r){var a=r.split("|");return {n:a[0],c:a[1],la:+a[2],lo:+a[3]}});\n'
      '  /* the nearest, and how far (km), along the Earth */\n'
      '  function near(lat,lon){var b=null,bd=1e9,c1=Math.cos(lat*Math.PI/180);for(var i=0;i<L.length;i++){var p=L[i],dy=p.la-lat,dx=((p.lo-lon+540)%360-180)*c1,d=dx*dx+dy*dy;if(d<bd){bd=d;b=p}}\n'
      '    if(!b)return null;var r=Math.PI/180,s=Math.sin((b.la-lat)*r/2),t=Math.sin((b.lo-lon)*r/2),h=s*s+Math.cos(lat*r)*Math.cos(b.la*r)*t*t;return {name:b.n,country:b.c,km:2*6371*Math.asin(Math.min(1,Math.sqrt(h)))}}\n'
      '  return {near:near,n:L.length}})();\n')
open('src/09-cities.js', 'w', encoding='utf-8').write(js)
print('cities', len(rows), len(js), 'bytes')

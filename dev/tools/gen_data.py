# builds src/00-data.js: the real star catalogue and the band's onsets and envelopes (nine players, no horns).
# (What changes by the hour, the orbits, wind, aurora and lightning, is not here: see tools/feed.py and tools/gen_live.py.)
# usage: python3 -I tools/gen_data.py            (run from the folder that holds src/, data/ and tools/)
import json, base64, struct, sys, os, datetime
R = 'raw/'
out = []

# The star catalogue never changes, so when the raw files are not at hand (a later session that only wants to refresh the feed)
# the three star lines are taken as they stand from the existing src/00-data.js.
if os.path.exists(R + 'stars.6.json'):
    # ---- stars: XHIP (Extended Hipparcos Compilation) via d3-celestial's stars.6.json: 5044 stars to magnitude 6 ----
    stars = json.load(open(R + 'stars.6.json', encoding='utf-8'))['features']
    names = json.load(open(R + 'starnames.json', encoding='utf-8'))
    rows = []
    for f in stars:
        lon, lat = f['geometry']['coordinates']
        ra = (lon + 360.0) % 360.0
        mag = float(f['properties']['mag'])
        try: bv = float(f['properties']['bv'])
        except Exception: bv = 0.6
        rows.append((mag, ra, lat, bv, str(f['id'])))
    rows.sort()
    buf = bytearray()
    for mag, ra, dec, bv, hid in rows:
        buf += struct.pack('<HhBB', min(65535, int(round(ra / 360.0 * 65536)) % 65536), int(round(dec / 90.0 * 32767)),
                           max(0, min(255, int(round((mag + 1.5) / 8.0 * 255)))), max(0, min(255, int(round((bv + 0.4) / 2.4 * 255)))))
    out.append('var STARS_B64="%s";' % base64.b64encode(bytes(buf)).decode())

else:
    keep = [l for l in open('src/00-data.js', encoding='utf-8').read().split('\n') if l.startswith('var STARS_B64=')]
    assert len(keep) == 1, 'src/00-data.js has no star line to reuse: fetch the raw catalogue (see REFERENCES.md)'
    out += keep; rows = []; named = []; nseg = 0

# ---- the band: per-player onsets and loudness envelopes read off the recordings; the horn section (old index 8) is left out ----
bd = json.load(open('data/band_data.json'))
keep = [0, 1, 2, 3, 4, 5, 6, 7, 9]
out.append('var BAND_DATA=%s;' % json.dumps({'env': [bd['env'][i] for i in keep], 'ons': [bd['ons'][i] for i in keep]}, separators=(',', ':')))

# nothing that came from outside may end a script block
out = [o.replace('<', '\\u003c') for o in out]
open('src/00-data.js', 'w', encoding='utf-8').write('/* generated by tools/gen_data.py: do not edit */\n' + '\n'.join(out) + '\n')
print('stars', len(rows) or 'kept as they were')
print('bytes', os.path.getsize('src/00-data.js'))
